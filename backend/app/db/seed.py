logger = get_logger(__name__)


def seed_database(session: Session, settings: Settings) -> None:
    """Create a realistic demo dataset and initial scoring decisions."""

    repository = LeadRepository(session)
    if repository.count_leads() > 0:
        return

    service = LeadService(session, settings)
    seeded = 0
    for payload in build_seed_leads():
        decision = service.score_lead(payload, is_seeded=True)
        seeded += 1
        if payload.historical_outcome:
            reason_map = {
                "converted": "Observed opportunity progressed to signed deal after follow-up.",
                "not_converted": "Account stalled after pricing and change-management review.",
                "disqualified": "Account was disqualified due to timing, fit, or compliance blockers.",
            }
            service.record_feedback(
                decision.lead_id,
                FeedbackRequest(
                    outcome=payload.historical_outcome,
                    reason=reason_map[payload.historical_outcome],
                    conversion_value=round(payload.budget_estimate * 1.35, 2)
                    if payload.historical_outcome == "converted"
                    else None,
                    salesperson_feedback=(
                        "Commercial signal matched field reality."
                        if payload.historical_outcome == "converted"
                        else "Buyer intent was softer than initial score suggested."
                    ),
                ),
            )
    logger.info("Seeded %s demo leads into the local database.", seeded)


